/**
 * Normaliza o identificador numérico do artigo (ex: "Art. 3", "3º", "3" -> "3")
 */
export function extractArticleNumKey(numero: string): string {
  if (!numero) return '';
  const match = numero.match(/\b(\d+(?:-[A-Za-z0-9]+)?)\b/);
  return match ? match[1].toUpperCase() : numero.trim();
}

/**
 * Obtém o Nomen Juris oficial para uma determinada lei e número de artigo.
 */
export function getNomenJuris(leiSlugOrTabela?: string, numero?: string, fallbackEpigrafe?: string): string | null {
  if (!numero) return null;
  const key = extractArticleNumKey(numero);
  const slug = (leiSlugOrTabela || '').toLowerCase();
  const isCP = slug === 'cp' || slug === 'codigo-penal' || slug.includes('cp_codigo_penal');
  const isCPM = slug === 'cpm' || slug === 'codigo-penal-militar' || slug.includes('cpm_codigo_penal_militar');

  if (isCP) {
    if (NOMEN_JURIS_CP[key]) return NOMEN_JURIS_CP[key];
  } else if (isCPM) {
    if (NOMEN_JURIS_CPM[key]) return NOMEN_JURIS_CPM[key];
  }

  // Fallback para epígrafe existente vinda do banco se for válida e não for estrutural
  if (fallbackEpigrafe && fallbackEpigrafe.trim().length > 0) {
    const clean = fallbackEpigrafe.trim();
    if (!/^(PARTE|LIVRO|T[IÍ]TULO|CAP[IÍ]TULO|SEÇ[AÃ]O|SUBSEÇ[AÃ]O)\b/i.test(clean)) {
      return clean;
    }
  }

  return null;
}

